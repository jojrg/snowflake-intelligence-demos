    ARRAY_CONSTRUCT('de','nl','fr','uk'), TRUE
  );
-- Child: run transformation right after ingestion completes
CREATE OR ALTER TASK AI_DEVELOPMENT.SI_ENERGY_TRADING_COMPANY.TASK_TRANSFORM_MARKET_DATA_FROM_VIEWS_FORECAST
  WAREHOUSE = COMPUTE_WH
  AFTER AI_DEVELOPMENT.SI_ENERGY_TRADING_COMPANY.TASK_INGEST_FORECAST_ENDPOINTS
AS
BEGIN
  CALL AI_DEVELOPMENT.SI_ENERGY_TRADING_COMPANY.TRANSFORM_MARKET_DATA_FROM_VIEWS(FALSE);
END;


