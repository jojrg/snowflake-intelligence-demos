-- Parent: nightly ingestion of raw endpoints for DE, NL, FR, UK
CREATE OR ALTER TASK AI_DEVELOPMENT.SI_ENERGY_TRADING_COMPANY.TASK_INGEST_HISTORICAL_ENDPOINTS_RAW
  WAREHOUSE = AI_WH
  SCHEDULE = 'USING CRON 0 3 * * * Europe/Berlin'
AS
  CALL AI_DEVELOPMENT.SI_ENERGY_TRADING_COMPANY.INGEST_HISTORICAL_ENDPOINTS_RAW(
    ARRAY_CONSTRUCT('de','nl','fr','uk'), TRUE, TRUE, NULL, NULL
  );


-- Child: run transformation right after ingestion completes
CREATE OR ALTER TASK AI_DEVELOPMENT.SI_ENERGY_TRADING_COMPANY.TASK_TRANSFORM_MARKET_DATA_FROM_VIEWS_HISTORICAL
  WAREHOUSE = COMPUTE_WH
  AFTER AI_DEVELOPMENT.SI_ENERGY_TRADING_COMPANY.TASK_INGEST_HISTORICAL_ENDPOINTS_RAW
AS
BEGIN
  CALL AI_DEVELOPMENT.SI_ENERGY_TRADING_COMPANY.TRANSFORM_MARKET_DATA_FROM_VIEWS(FALSE);

END;

-- Enable the task chain (does not run immediately; just schedules future runs)


CREATE OR ALTER TASK AI_DEVELOPMENT.SI_ENERGY_TRADING_COMPANY.TASK_INGEST_FORECAST_ENDPOINTS
  WAREHOUSE = AI_WH
  SCHEDULE = 'USING CRON 0 3 * * * Europe/Berlin'
AS
